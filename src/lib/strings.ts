export type StringKey = keyof typeof en

export type Params = Partial<Record<'year' | 'span' | 'time' | 'city' | 'country', string | number>>

/** One translated, filled-in string; anything missing falls back to English. */
export function translate(lang: string, key: StringKey, params: Params = {}): string {
  const template = TABLES[lang]?.[key] ?? en[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name as keyof Params] ?? ''))
}

/** The compact unit letters for spans ("3h 12m"): days, hours, minutes, seconds. */
export const spanUnits = (lang: string): [string, string, string, string] =>
  (TABLES[lang]?.abbr ?? en.abbr).split('|') as [string, string, string, string]

/** `t('key', {params})` in the current language; the caller re-renders when the language changes. */
export function useT() {
  const lang = useLanguage()
  const t = useCallback((key: StringKey, params?: Params) => translate(lang, key, params), [lang])
  return { t, lang }
}
